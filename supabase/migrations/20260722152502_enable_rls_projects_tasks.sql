-- Включает Row Level Security на public.projects и public.tasks без добавления политик
-- (модель "deny by default"): при RLS включённом и без единой политики Postgres запрещает
-- доступ всем ролям к этой таблице через обычные запросы, кроме владельца таблицы,
-- суперпользователя и ролей с BYPASSRLS (в частности service_role, которым пользуются
-- Edge Functions — на их работу это никак не влияет).
--
-- Причина: обе таблицы до этой миграции имели RLS выключенным, при этом роль anon имела
-- полный табличный грант (SELECT/INSERT/UPDATE/DELETE), то есть были публично читаемы и
-- доступны на запись без какой-либо авторизации. Подтверждено вживую анонимным запросом
-- (см. docs/RLS_AUDIT.md).
--
-- Обе таблицы не используются нигде в приложении: read-only проверкой (повторно перед этой
-- миграцией) подтверждено отсутствие обращений к ним в коде фронтенда (app/src), во всех
-- 6 задеплоенных Edge Functions (включая scan-invoice и super-service, которых нет в этом
-- репозитории) и во всех 6 пользовательских RPC/триггерных функций проекта. См.
-- docs/RLS_AUDIT.md и docs/STORAGE_PRIVACY_PLAN.md, раздел 7 — план и обоснование этого шага.
--
-- Политики намеренно не добавляются: если в будущем понадобится дать доступ какой-либо роли
-- к этим таблицам, это отдельное решение (см. docs/decisions/), а не часть данной миграции.

alter table public.projects enable row level security

alter table public.tasks enable row level security

